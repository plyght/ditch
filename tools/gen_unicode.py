#!/usr/bin/env python3
"""Regenerates src/unicode_tables.zig from Python's unicodedata: the Unicode
letter/number/whitespace ranges used by the pre-tokenisers and the per-code-point
"fold" mapping (NFKD, then drop nonspacing marks, then lowercase every char) that
DeepSeek-V4.1 uses to build the compressed token map of its engram hash layers.
Hangul syllables fold algorithmically and are not in the table."""
import unicodedata
def ranges(pred):
    out=[]; start=None
    for cp in range(0x110000):
        ok=pred(cp)
        if ok and start is None: start=cp
        if not ok and start is not None: out.append((start,cp-1)); start=None
    if start is not None: out.append((start,0x10FFFF))
    return out
L=ranges(lambda c: unicodedata.category(chr(c)).startswith('L'))
N=ranges(lambda c: unicodedata.category(chr(c)).startswith('N'))
S=ranges(lambda c: chr(c).isspace())
def emit(name, rs):
    lines=[f"pub const {name} = [_]Range{{"]
    for a,b in rs: lines.append(f"    .{{ .lo = 0x{a:X}, .hi = 0x{b:X} }},")
    lines.append("};")
    return "\n".join(lines)
def fold(cp):
    s=unicodedata.normalize('NFKD',chr(cp))
    s=''.join(x for x in s if unicodedata.category(x)!='Mn')
    return ''.join(x.lower() for x in s)
entries=[(cp,fold(cp)) for cp in range(0x110000) if not (0xAC00<=cp<=0xD7A3) and fold(cp)!=chr(cp)]
runs=[]; drops=[]; multi=[]
i=0
while i<len(entries):
    cp,s=entries[i]
    if len(s)==1:
        delta=ord(s)-cp; j=i+1
        while j<len(entries) and entries[j][0]==entries[j-1][0]+1 and len(entries[j][1])==1 and ord(entries[j][1])-entries[j][0]==delta: j+=1
        runs.append((cp,entries[j-1][0],delta)); i=j
    elif len(s)==0:
        j=i+1
        while j<len(entries) and entries[j][0]==entries[j-1][0]+1 and len(entries[j][1])==0: j+=1
        drops.append((cp,entries[j-1][0])); i=j
    else:
        multi.append((cp,s)); i+=1
def zstr(s):
    return '"' + ''.join('\\x%02x' % b for b in s.encode()) + '"'
src = "//! Generated by tools/gen_unicode.py from Python's unicodedata (Unicode %s). Do not edit.\n" % unicodedata.unidata_version
src += "pub const Range = struct { lo: u21, hi: u21 };\n\n"
src += emit("letters", L) + "\n\n" + emit("numbers", N) + "\n\n" + emit("whitespace", S) + "\n\n"
src += "/// Code points `lo..hi` whose fold is the single code point `cp + delta`.\n"
src += "pub const FoldRun = struct { lo: u21, hi: u21, delta: i32 };\n"
src += "pub const fold_runs = [_]FoldRun{\n" + "\n".join(f"    .{{ .lo = 0x{a:X}, .hi = 0x{b:X}, .delta = {d} }}," for a,b,d in runs) + "\n};\n\n"
src += "/// Code points whose fold is empty (nonspacing marks).\n"
src += emit("fold_drop", drops) + "\n\n"
src += "/// Code points whose fold is several code points (UTF-8).\n"
src += "pub const FoldMulti = struct { cp: u21, out: []const u8 };\n"
src += "pub const fold_multi = [_]FoldMulti{\n" + "\n".join(f"    .{{ .cp = 0x{cp:X}, .out = {zstr(s)} }}," for cp,s in multi) + "\n};\n"
open("src/unicode_tables.zig","w").write(src)
